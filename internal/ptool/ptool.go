// Package ptool finds and runs the P tool, `p`, for plsp's type checks and
// prdb's replays.
package ptool

import (
	"os"
	"os/exec"
	"path/filepath"
)

// Find returns the command that runs the P tool, given as command, and the
// environment to run it in, or nil for this process's own.
//
// Editors started from a desktop often lack the PATH and DOTNET_ROOT a
// shell profile sets, so when command is the default "p" and isn't on the
// PATH, Find looks where `dotnet tool install --global` puts it, and runs
// it with the .NET it was installed with. Otherwise, it returns the error
// from looking command up.
func Find(command []string) ([]string, []string, error) {
	_, err := exec.LookPath(command[0])
	if err == nil || command[0] != "p" {
		return command, nil, err
	}
	home, homeErr := os.UserHomeDir()
	if homeErr != nil {
		return nil, nil, err
	}
	tool := filepath.Join(home, ".dotnet", "tools", "p")
	if _, statErr := os.Stat(tool); statErr != nil {
		return nil, nil, err
	}
	found := append([]string{tool}, command[1:]...)
	root := os.Getenv("DOTNET_ROOT")
	if root == "" {
		root = filepath.Join(home, ".dotnet")
	}
	if _, statErr := os.Stat(filepath.Join(root, "dotnet")); statErr != nil {
		return found, nil, nil
	}
	env := append(os.Environ(), "DOTNET_ROOT="+root, "PATH="+root+string(os.PathListSeparator)+os.Getenv("PATH"))
	return found, env, nil
}

// Names returns the names of the entries in dir, to pass to RemoveNewEmpty
// after running the compiler.
func Names(dir string) map[string]bool {
	names := map[string]bool{}
	list, _ := os.ReadDir(dir)
	for _, e := range list {
		names[e.Name()] = true
	}
	return names
}

// RemoveNewEmpty removes the empty directories in dir that weren't among
// before. Builds go to temporary directories, but the compiler still makes
// the project's output directory, PGenerated by default.
func RemoveNewEmpty(dir string, before map[string]bool) {
	list, _ := os.ReadDir(dir)
	for _, e := range list {
		if e.IsDir() && !before[e.Name()] {
			os.Remove(filepath.Join(dir, e.Name())) // fails unless empty
		}
	}
}
